"use client";

import * as React from "react";
import { motion } from "framer-motion";
import {
  FileText,
  Download,
  FileSpreadsheet,
  File as FileIcon,
  Plus,
  CheckCircle2,
  Loader2,
  Database,
  BarChart3,
  Brain,
  Activity,
  ShieldCheck,
} from "lucide-react";
import { useAppStore } from "@/lib/store";
import { Card, CardContent, CardHeader, CardTitle, CardDescription } from "@/components/ui/card";
import { Button } from "@/components/ui/button";
import { Badge } from "@/components/ui/badge";
import {
  Dialog,
  DialogContent,
  DialogHeader,
  DialogTitle,
  DialogDescription,
  DialogFooter,
} from "@/components/ui/dialog";
import { useToast } from "@/hooks/use-toast";
import { cn } from "@/lib/utils";
import { STUDY_META } from "@/lib/types";

const REPORT_TYPES = [
  { type: "Study Dataset Summary", icon: Database, desc: "Records, eligibility, completeness" },
  { type: "Model Performance Report", icon: Activity, desc: "ROC, confusion matrix, metrics" },
  { type: "Prediction Analysis", icon: Brain, desc: "AI predictions vs documented outcomes" },
  { type: "Feature Analysis", icon: BarChart3, desc: "Importance, SHAP, distributions" },
  { type: "Data Quality Report", icon: ShieldCheck, desc: "Validation, missing, duplicates" },
  { type: "Final Research Summary", icon: FileText, desc: "Comprehensive study summary" },
];

export function ReportsView() {
  const { reports, addReport, addAuditLog, currentUser } = useAppStore();
  const { toast } = useToast();
  const [genOpen, setGenOpen] = React.useState(false);
  const [selected, setSelected] = React.useState<typeof REPORT_TYPES[number] | null>(null);
  const [generating, setGenerating] = React.useState(false);

  function generate(format: "PDF" | "Excel" | "CSV") {
    if (!selected) return;
    setGenerating(true);
    setTimeout(() => {
      addReport({
        id: `r_${Date.now()}`,
        type: selected.type,
        generatedBy: currentUser.name,
        generatedAt: new Date().toISOString(),
        format,
        records: selected.type.includes("Model") ? 3 : 128,
        status: "Ready",
      });
      addAuditLog({
        timestamp: new Date().toISOString(),
        user: currentUser.name,
        action: "Generated report",
        module: "Reports",
        caseId: null,
        status: "Success",
        detail: `${selected.type} (${format})`,
      });
      setGenerating(false);
      setGenOpen(false);
      toast({ title: "Report generated", description: `${selected.type} (${format}) is ready.` });
    }, 1200);
  }

  return (
    <div className="space-y-4">
      <div className="grid grid-cols-1 gap-3 sm:grid-cols-2 lg:grid-cols-3">
        {REPORT_TYPES.map((rt, i) => (
          <motion.div key={rt.type} initial={{ opacity: 0, y: 8 }} animate={{ opacity: 1, y: 0 }} transition={{ delay: i * 0.05 }}>
            <Card className="group h-full transition-shadow hover:shadow-lg">
              <CardContent className="flex h-full flex-col p-4">
                <div className="flex items-start justify-between">
                  <div className="grid h-10 w-10 place-items-center rounded-xl bg-brand-gradient-soft text-primary">
                    <rt.icon className="h-5 w-5" />
                  </div>
                  <Button variant="ghost" size="sm" onClick={() => { setSelected(rt); setGenOpen(true); }}>
                    <Plus className="h-3.5 w-3.5" /> Generate
                  </Button>
                </div>
                <p className="mt-3 text-sm font-semibold text-foreground">{rt.type}</p>
                <p className="mt-0.5 text-xs text-muted-foreground">{rt.desc}</p>
              </CardContent>
            </Card>
          </motion.div>
        ))}
      </div>

      <Card>
        <CardHeader><CardTitle>Generated Reports</CardTitle><CardDescription>Recently generated research reports</CardDescription></CardHeader>
        <CardContent className="px-0">
          <div className="overflow-x-auto scrollbar-medical">
            <table className="w-full text-sm">
              <thead>
                <tr className="border-b border-border text-left text-[11px] uppercase tracking-wide text-muted-foreground">
                  <th className="px-6 py-2.5 font-medium">Report</th>
                  <th className="px-3 py-2.5 font-medium">Generated By</th>
                  <th className="px-3 py-2.5 font-medium">Format</th>
                  <th className="px-3 py-2.5 font-medium">Records</th>
                  <th className="px-3 py-2.5 font-medium">Status</th>
                  <th className="px-3 py-2.5 font-medium">Date</th>
                  <th className="px-6 py-2.5 font-medium text-right">Actions</th>
                </tr>
              </thead>
              <tbody>
                {reports.map((r) => (
                  <tr key={r.id} className="border-b border-border/60 hover:bg-muted/40">
                    <td className="px-6 py-3">
                      <div className="flex items-center gap-2">
                        {r.format === "PDF" ? <FileText className="h-4 w-4 text-red-500" /> : r.format === "Excel" ? <FileSpreadsheet className="h-4 w-4 text-emerald-600" /> : <FileIcon className="h-4 w-4 text-blue-600" />}
                        <span className="text-sm font-medium text-foreground">{r.type}</span>
                      </div>
                    </td>
                    <td className="px-3 py-3 text-muted-foreground">{r.generatedBy}</td>
                    <td className="px-3 py-3"><Badge variant="outline" className="text-[10px]">{r.format}</Badge></td>
                    <td className="px-3 py-3 tabular-nums">{r.records}</td>
                    <td className="px-3 py-3">
                      {r.status === "Ready" ? (
                        <Badge className="bg-emerald-100 text-emerald-700"><CheckCircle2 className="h-3 w-3" /> Ready</Badge>
                      ) : (
                        <Badge variant="secondary" className="gap-1"><Loader2 className="h-3 w-3 animate-spin" /> Generating</Badge>
                      )}
                    </td>
                    <td className="px-3 py-3 text-xs text-muted-foreground">{r.generatedAt.slice(0, 10)}</td>
                    <td className="px-6 py-3">
                      <div className="flex justify-end gap-1">
                        <button className="grid h-7 w-7 place-items-center rounded-md text-muted-foreground hover:bg-primary/10 hover:text-primary" title="Download" onClick={() => toast({ title: "Download started", description: r.type })}><Download className="h-3.5 w-3.5" /></button>
                      </div>
                    </td>
                  </tr>
                ))}
              </tbody>
            </table>
          </div>
        </CardContent>
      </Card>

      <GenerateDialog open={genOpen} onClose={() => setGenOpen(false)} selected={selected} generating={generating} generate={generate} />
    </div>
  );
}

function GenerateDialog({ open, onClose, selected, generating, generate }: {
  open: boolean;
  onClose: () => void;
  selected: typeof REPORT_TYPES[number] | null;
  generating: boolean;
  generate: (f: "PDF" | "Excel" | "CSV") => void;
}) {
  return (
    <Dialog open={open} onOpenChange={(o) => { if (!o) onClose(); }}>
      <DialogContent className="max-w-lg">
        <DialogHeader>
          <DialogTitle>Generate {selected?.type}</DialogTitle>
          <DialogDescription>{selected?.desc}</DialogDescription>
        </DialogHeader>
        <div className="space-y-2">
          <p className="text-xs text-muted-foreground">PDF report includes: institution/project title, study title, date, dataset summary, methods, model information, performance metrics, charts, limitations, and research-use disclaimer.</p>
          <div className="rounded-lg border border-amber-200 bg-amber-50 px-3 py-2 text-[11px] text-amber-800">
            {STUDY_META.disclaimer} No unsupported clinical conclusions are generated automatically.
          </div>
        </div>
        <DialogFooter className="flex-wrap gap-2 sm:gap-2">
          <Button variant="outline" size="sm" disabled={generating} onClick={() => generate("CSV")}>
            {generating ? <Loader2 className="h-4 w-4 animate-spin" /> : <Download className="h-4 w-4" />} Export CSV
          </Button>
          <Button variant="outline" size="sm" disabled={generating} onClick={() => generate("Excel")}>
            {generating ? <Loader2 className="h-4 w-4 animate-spin" /> : <FileSpreadsheet className="h-4 w-4" />} Export Excel
          </Button>
          <Button size="sm" className="bg-brand-gradient text-white" disabled={generating} onClick={() => generate("PDF")}>
            {generating ? <Loader2 className="h-4 w-4 animate-spin" /> : <FileText className="h-4 w-4" />} Generate PDF
          </Button>
        </DialogFooter>
      </DialogContent>
    </Dialog>
  );
}
